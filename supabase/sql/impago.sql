-- Iberail · plaza cancelada por impago + apelación del cliente (assets/panel.js + assets/cuenta.js)
-- Ejecutar UNA vez en Supabase → SQL Editor.
--
-- El equipo marca a una persona de un grupo como «Cancelado por impago» (no ha pagado a tiempo).
-- Todo el grupo ve la etiqueta junto a su nombre en «Pagos del grupo»; la persona ve el motivo y puede
-- «Solicitar apelación» con un texto. El equipo la acepta (se revoca la cancelación) o la rechaza (se mantiene).
--
-- estado:  cancelado  → recién marcada; la persona puede apelar
--          apelada    → ha pedido la apelación; la revisa el equipo
--          confirmada → apelación rechazada; la cancelación se mantiene y no se puede volver a apelar
--          revocada   → ya no está cancelada (apelación aceptada o el equipo la quitó); se guarda como historial

create table if not exists public.cancelaciones (
  id            bigint generated by default as identity primary key,
  grupo_id      bigint not null references public.grupos(id) on delete cascade,
  user_id       uuid not null references auth.users(id) on delete cascade,
  motivo        text not null default 'No ha pagado a tiempo' check (char_length(motivo) <= 300),
  estado        text not null default 'cancelado' check (estado in ('cancelado', 'apelada', 'confirmada', 'revocada')),
  apelacion     text check (char_length(apelacion) <= 1000),
  apelacion_at  timestamptz,
  respuesta     text check (char_length(respuesta) <= 1000),
  resuelta_at   timestamptz,
  resuelta_por  uuid references auth.users(id) on delete set null,
  creada_por    uuid default auth.uid() references auth.users(id) on delete set null,
  created_at    timestamptz not null default now()
);
create index if not exists cancelaciones_grupo_idx on public.cancelaciones (grupo_id);
-- como mucho una cancelación vigente por persona y grupo (las revocadas se quedan de historial)
create unique index if not exists cancelaciones_vigente_uq on public.cancelaciones (grupo_id, user_id)
  where estado <> 'revocada';

-- quién ve qué: cada uno su propia cancelación; el equipo todo (y es el único que crea, cambia o borra)
alter table public.cancelaciones enable row level security;
drop policy if exists "cancelaciones: la mía" on public.cancelaciones;
create policy "cancelaciones: la mía" on public.cancelaciones for select to authenticated
  using (user_id = auth.uid() or public.is_admin());
drop policy if exists "cancelaciones: equipo" on public.cancelaciones;
create policy "cancelaciones: equipo" on public.cancelaciones for all to authenticated
  using (public.is_admin()) with check (public.is_admin());

-- quién del equipo lo resuelve y cuándo (al pasar a «confirmada» o «revocada»)
create or replace function public.cancelaciones_resuelta() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.estado in ('confirmada', 'revocada') and new.estado is distinct from old.estado then
    new.resuelta_at := now();
    new.resuelta_por := auth.uid();
  end if;
  return new;
end;
$$;
drop trigger if exists cancelaciones_resuelta on public.cancelaciones;
create trigger cancelaciones_resuelta before update on public.cancelaciones
  for each row execute function public.cancelaciones_resuelta();

-- lo que ve el resto del grupo: solo quién está cancelado y en qué punto (nunca el motivo ni el texto de la apelación)
create or replace function public.cancelados_grupo(g bigint)
returns table (user_id uuid, estado text)
language sql stable security definer set search_path = public as $$
  select c.user_id, c.estado
  from public.cancelaciones c
  where c.grupo_id = g and c.estado <> 'revocada'
    and (public.is_admin() or exists (select 1 from public.grupo_miembros m where m.grupo_id = g and m.user_id = auth.uid()));
$$;
revoke all on function public.cancelados_grupo(bigint) from public, anon;
grant execute on function public.cancelados_grupo(bigint) to authenticated;

-- la persona cancelada pide la apelación (solo la suya, solo una vez y solo mientras esté «cancelado»)
create or replace function public.apelar_cancelacion(c bigint, texto text)
returns public.cancelaciones
language plpgsql security definer set search_path = public as $$
declare fila public.cancelaciones;
begin
  if char_length(btrim(coalesce(texto, ''))) < 10 then
    raise exception 'Cuéntanos un poco más (mínimo 10 caracteres).';
  end if;
  update public.cancelaciones
     set estado = 'apelada', apelacion = left(btrim(texto), 1000), apelacion_at = now()
   where id = c and user_id = auth.uid() and estado = 'cancelado'
  returning * into fila;
  if not found then
    raise exception 'Esta cancelación ya no se puede apelar.';
  end if;
  -- que salga en «En directo» del panel (si la tabla de actividad existe)
  begin
    insert into public.actividad (user_id, tipo, pagina, detalle)
    values (auth.uid(), 'apelacion_impago', 'grupos', jsonb_build_object('grupo_id', fila.grupo_id, 'cancelacion', fila.id));
  exception when undefined_table then null;
  end;
  return fila;
end;
$$;
revoke all on function public.apelar_cancelacion(bigint, text) from public, anon;
grant execute on function public.apelar_cancelacion(bigint, text) to authenticated;

-- que el panel y la cuenta lo vean al momento
do $$ begin
  alter publication supabase_realtime add table public.cancelaciones;
exception when duplicate_object then null; end $$;
